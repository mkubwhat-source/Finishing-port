def remap_item(i):
    """Item id -> bundle id; raises Dropped for items with no counterpart."""
    i = VANILLA_RENAMES.get(norm(i), norm(i))
    if i in DROPPED:
        raise Dropped(i)
    ns, p = ns_path(i)
    if ns == "farmersdelight":
        if i in FD_TO_BUNDLE_ITEMS:
            return FD_TO_BUNDLE_ITEMS[i]
        if p in HH_ITEMS:
            return HH + ":" + p
        raise Dropped(i)
    if ns == HH:
        p = HH_RENAMES.get(p, p)
        if p in HH_MERGED_ITEMS:
            return HH_MERGED_ITEMS[p]
        return HH + ":" + p
    return i


def remap_block(i):
    i = VANILLA_RENAMES.get(norm(i), norm(i))
    if i in DROPPED:
        raise Dropped(i)
    ns, p = ns_path(i)
    if ns == "farmersdelight":
        if i in FD_TO_BUNDLE_BLOCKS:
            return FD_TO_BUNDLE_BLOCKS[i]
        if p in HH_BLOCKS:
            return HH + ":" + p
        raise Dropped(i)
    if ns == HH:
        p = HH_RENAMES.get(p, p)
        return HH_MERGED_BLOCKS.get(p, HH + ":" + p)
    return i


def remap_tag(t):
    """A tag id (no '#'). FD's own tags moved to the hearthandharvest namespace (FDTags)."""
    ns, p = ns_path(t)
    if ns == "farmersdelight":
        return HH + ":" + p
    if t == "c:flours":     # HH used c:flours (+ c:flours/wheat, c:flours/corn); BF/Flavored use c:flour
        return t
    return t


def remap_ref(s, kind):
    """'#tag' or id, of kind 'item'/'block'."""
    if s.startswith("#"):
        return "#" + remap_tag(s[1:])
    return remap_item(s) if kind == "item" else remap_block(s)


def check_known(i, kind):
    known = KNOWN_ITEMS if kind == "item" else KNOWN_BLOCKS
    if not i.startswith("#") and i not in known:
        raise Dropped(i)
    return i


# ----------------------------------------------------------------------------- ingredients/recipes

def ingredient(i):
    """1.21.1 ingredient -> 26.3 (string, list of strings, or Fabric custom object)."""
    if isinstance(i, list):
        out = []
        for x in i:
            try:
                out.append(ingredient(x))
            except Dropped as e:
                REPORT["ingredient alternative dropped"].append(str(e))
        if not out:
            raise Dropped("empty ingredient list")
        flat = []
        for x in out:
            if isinstance(x, list):
                flat += x
            elif isinstance(x, dict):
                if len(out) == 1:
                    return x
                raise ValueError("custom ingredient inside a list: %r" % i)
            else:
                flat.append(x)
        return flat[0] if len(flat) == 1 else flat
    if isinstance(i, str):
        r = check_known(remap_ref(i, "item"), "item")
        return INGREDIENT_REMAP.get(r, r)
    t = i.get("type") or i.get("fabric:type")
    if t in ("hearthandharvest:vintage",):
        return {"fabric:type": "hearthandharvest:vintage", "base": ingredient(i["base"]), "vintage": i["vintage"]}
    if t in ("farmersdelight:item_ability", "hearthandharvest:item_ability"):
        return {"fabric:type": "hearthandharvest:item_ability", "action": i["action"]}
    if t == "neoforge:components":
        out = {"fabric:type": "fabric:components", "base": ingredient(i["items"]), "components": i["components"]}
        return out
    if t is not None:
        raise ValueError("unhandled ingredient type %s" % t)
    if "item" in i:
        r = check_known(remap_item(i["item"]), "item")
        return INGREDIENT_REMAP.get(r, r)
    if "tag" in i:
        return "#" + remap_tag(i["tag"])
    raise ValueError("unhandled ingredient %r" % i)


def stack(s, key="id"):
    s = dict(s)
    s[key] = check_known(remap_item(s[key]), "item")
    if s.get("count") == 1:
        del s["count"]
    return s


def conditions_to_fabric(r):
    conds = r.pop("neoforge:conditions", None)
    if not conds:
        return r
    mods = []
    for c in conds:
        if c.get("type") == "neoforge:mod_loaded":
            mods.append(c["modid"])
        else:
            raise ValueError("unhandled condition %r" % c)
    return {"fabric:load_conditions": [{"condition": "fabric:all_mods_loaded", "values": mods}], **r}


INTEGRATION_MODS = {"create", "brewinandchewin", "botanypots", "berry_good", "crabbersdelight"}


FLUID_REMAP = {"minecraft:milk": "hearthandharvest:milk"}  # NeoForge's milk fluid; HH registers its own on Fabric


def recipe(r):
    r = conditions_to_fabric(copy.deepcopy(r))
    for k in ("input_fluid", "result_fluid"):
        if isinstance(r.get(k), dict) and "id" in r[k]:
            r[k]["id"] = FLUID_REMAP.get(r[k]["id"], r[k]["id"])
    cond_mods = set()
    for c in r.get("fabric:load_conditions", []):
        cond_mods.update(c["values"])
    t = r["type"]
    if t.split(":")[0] in INTEGRATION_MODS or cond_mods & INTEGRATION_MODS:
        # Another mod's format / a conditional HH recipe: ids only (formats of those mods unknown on 26.3).
        return remap_loose(r)
    if t in ("farmersdelight:cooking", "farmersdelight:cutting"):
        r["type"] = HH + ":" + t.split(":")[1]
    t = r["type"]
    if "key" in r:
        r["key"] = {k: ingredient(v) for k, v in r["key"].items()}
    for k in ("ingredient", "base", "addition", "template", "tool", "salt", "input"):
        if k in r:
            r[k] = ingredient(r[k])
    if "ingredients" in r:
        r["ingredients"] = [ingredient(x) for x in r["ingredients"]]
    if t == HH + ":cutting":
        out = []
        for res in r["result"]:
            try:
                res = dict(res)
                res["item"] = stack(res["item"])
                out.append(res)
            except Dropped as e:
                REPORT["cutting result dropped"].append(str(e))
        if not out:
            raise Dropped("no cutting results")
        r["result"] = out
    else:
        for k in ("result", "result_item", "container"):
            if k in r and isinstance(r[k], dict):
                r[k] = stack(r[k])
    return r


def remap_loose(o):
    """Remap ids found anywhere (for other mods' recipe formats). Leaves unknown strings alone."""
    if isinstance(o, dict):
        return {k: remap_loose(v) for k, v in o.items()}
    if isinstance(o, list):
        return [remap_loose(v) for v in o]
    if isinstance(o, str) and re.fullmatch(r"(farmersdelight|hearthandharvest):[a-z0-9_/]+", o):
        try:
            return remap_item(o)
        except Dropped:
            return o
    return o


# ----------------------------------------------------------------------------- loot/advancements

def remap_ids_in(o, kind="item"):
    """Remap item ids in advancement/loot predicate structures ("items": str|list, "id", "name")."""
    if isinstance(o, dict):
        out = {}
        for k, v in o.items():
            if k in ("items",) and isinstance(v, str):
                out[k] = check_known(remap_ref(v, "item"), "item")
            elif k in ("items",) and isinstance(v, list) and all(isinstance(x, str) for x in v):
                out[k] = [check_known(remap_ref(x, "item"), "item") for x in v]
            elif k == "blocks" and isinstance(v, (str, list)):
                vs = [v] if isinstance(v, str) else v
                vs = [check_known(remap_ref(x, "block"), "block") for x in vs]
                out[k] = vs[0] if isinstance(v, str) else vs
            elif k == "block" and isinstance(v, str):
                out[k] = check_known(remap_block(v), "block")
            elif k == "id" and isinstance(v, str) and ":" in v and "count" in o or k == "id" and set(o) <= {"id", "count", "components"}:
                out[k] = check_known(remap_item(v), "item")
            elif k == "recipes" or k == "recipe":
                out[k] = v
            elif k == "tag" and isinstance(v, str):
                out[k] = remap_tag(v)
            else:
                out[k] = remap_ids_in(v, kind)
        return out
    if isinstance(o, list):
        return [remap_ids_in(v, kind) for v in o]
    return o


def loot_condition(c):
    c = dict(c)
    if c.get("type") == "neoforge:can_item_perform_ability":
        return {"type": HH + ":can_item_perform_ability", "ability": c["ability"]}
    return c


def loot_fix(o):
    if isinstance(o, dict):
        o = {k: loot_fix(v) for k, v in o.items()}
        if o.get("type") == "neoforge:can_item_perform_ability":
            o = loot_condition(o)
        if o.get("type") == "minecraft:match_tool" and "predicate" in o:
            o["predicate"] = item_predicate(o["predicate"])
        return o
    if isinstance(o, list):
        return [loot_fix(v) for v in o]
    return o


def item_predicate(p):
    p = dict(p)
    if "tag" in p and "items" not in p:
        p["items"] = "#" + remap_tag(p.pop("tag"))
    if "items" in p:
        v = p["items"]
        if isinstance(v, list):
            p["items"] = [remap_ref(x, "item") if isinstance(x, str) else x for x in v]
        else:
            p["items"] = remap_ref(v, "item")
    return p


def prune_entries(entries):
    out = []
    for e in entries:
        try:
            e = dict(e)
            if e.get("type") == "minecraft:item":
                e["name"] = check_known(remap_item(e["name"]), "item")
            if "children" in e:
                e["children"] = prune_entries(e["children"])
                if not e["children"]:
                    raise Dropped("no children")
            out.append(remap_ids_in(e))
        except Dropped as x:
            REPORT["loot entry dropped"].append(str(x))
    return out


def number_provider(v):
    """1.21.1 accepted untyped uniform/binomial number providers; 26.3 needs the type."""
    if isinstance(v, dict) and "type" not in v:
        if set(v) == {"min", "max"}:
            return {"type": "minecraft:uniform", **v}
        if set(v) == {"n", "p"}:
            return {"type": "minecraft:binomial", **v}
    return v


def fix_number_providers(t):
    for p in t.get("pools", []):
        for k in ("rolls", "bonus_rolls"):
            if k in p:
                p[k] = number_provider(p[k])

    def fns(o):
        if isinstance(o, dict):
            if o.get("function") in ("minecraft:set_count", "minecraft:set_damage", "minecraft:enchant_with_levels"):
                for k in ("count", "damage", "levels"):
                    if k in o:
                        o[k] = number_provider(o[k])
            for v in o.values():
                fns(v)
        elif isinstance(o, list):
            for v in o:
                fns(v)
    fns(t)
    return t


def loot_table(t):
    t = fix_number_providers(conditions_to_fabric(copy.deepcopy(t)))
    for p in t.get("pools", []):
        p.pop("name", None)
        p["entries"] = prune_entries(p["entries"])
    t["pools"] = [p for p in t.get("pools", []) if p["entries"]]
    out = dm.loot_table(t)
    return loot_fix(remap_ids_in(out))


def advancement(a):
    a = conditions_to_fabric(copy.deepcopy(a))
    for crit in a.get("criteria", {}).values():   # placed_block / item_used_on_block "location" lists
        c = crit.get("conditions", {})
        if isinstance(c.get("location"), list):
            c["location"] = dm.conditions(c["location"])
    a = dm.advancement(a)
    s = json.dumps(a)
    for k, v in ADVANCEMENT_ITEMS.items():
        s = s.replace('"%s"' % k, '"%s"' % v)
    a = json.loads(s)
    for c in a.get("criteria", {}).values():   # de-dup item lists after the trellis merge
        for it in c.get("conditions", {}).get("items", []) if isinstance(c.get("conditions", {}).get("items"), list) else []:
            if isinstance(it, dict) and isinstance(it.get("items"), list):
                it["items"] = list(dict.fromkeys(it["items"]))

    def preds(o):
        if isinstance(o, dict):
            if ("items" in o and not isinstance(o["items"], list) or isinstance(o.get("items"), list) and all(isinstance(x, str) for x in o["items"])) or "tag" in o:
                if set(o) <= {"items", "tag", "count", "components", "predicates", "durability"}:
                    o = item_predicate(o)
            return {k: preds(v) for k, v in o.items()}
        if isinstance(o, list):
            return [preds(v) for v in o]
        return o
    a = preds(a)
    # criteria: drop item criteria naming dropped items; keep advancement if any criterion survives
    crits = {}
    for name, c in a.get("criteria", {}).items():
        try:
            crits[name] = remap_ids_in(c)
        except Dropped as e:
            REPORT["advancement criterion dropped"].append(str(e))
    if not crits:
        raise Dropped("no criteria")
    if "requirements" in a:
        reqs = [[x for x in r if x in crits] for r in a["requirements"]]
        a["requirements"] = [r for r in reqs if r]
    a["criteria"] = crits
    if "display" in a and "icon" in a["display"]:
        ic = a["display"]["icon"]
        ic["id"] = remap_item(ic["id"])
        if ic.get("count") == 1:
            del ic["count"]
    return a


# ----------------------------------------------------------------------------- tags

def tag_values(values, kind, registry_known):
    out = []
    for v in values:
        req = True
        if isinstance(v, dict):
            req = v.get("required", True)
            v = v["id"]
        try:
            if v.startswith("#"):
                nv = "#" + remap_tag(v[1:])
            elif kind == "item":
                nv = remap_item(v)
            elif kind == "block":
                nv = remap_block(v)
            elif kind == "fluid":
                nv = FLUID_REMAP.get(v, v.replace("farmersdelight:", HH + ":"))
            else:
                nv = v.replace("farmersdelight:", HH + ":")
            if registry_known is not None and not nv.startswith("#") and nv not in registry_known:
                if req:
                    raise Dropped(nv)
            out.append(nv if req else {"id": nv, "required": False})
        except Dropped as e:
            REPORT["tag value dropped (%s)" % kind].append(str(e))
    # de-dup preserving order
    seen, res = set(), []
    for v in out:
        key = json.dumps(v)
        if key not in seen:
            seen.add(key)
            res.append(v)
    return res


