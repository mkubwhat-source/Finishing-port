def fdr_recipe(r):
    """FDR 26.3 recipe -> bundle: ids remapped; skipped if its result isn't a ported FD/HH item."""
    r = copy.deepcopy(r)
    orig_ings = {k: r[k] for k in ("key", "ingredients", "ingredient") if k in r}
    if r["type"].startswith("farmersdelight:"):
        r["type"] = r["type"].replace("farmersdelight:", HH + ":")
    if r["type"] not in ("minecraft:crafting_shaped", "minecraft:crafting_shapeless", "minecraft:smelting",
                         "minecraft:smoking", "minecraft:campfire_cooking", HH + ":cooking", HH + ":cutting"):
        raise Dropped("type " + r["type"])

    def ing(i):
        if isinstance(i, list):
            return [ing(x) for x in i]
        if isinstance(i, dict):
            if i.get("fabric:type") == "farmersdelight:item_ability":
                return {"fabric:type": HH + ":item_ability", "action": i["action"]}
            raise Dropped("custom ingredient %r" % i)
        return check_known(remap_ref(i, "item"), "item")
    if "key" in r:
        r["key"] = {k: ing(v) for k, v in r["key"].items()}
    for k in ("ingredient", "tool"):
        if k in r:
            r[k] = ing(r[k])
    if "ingredients" in r:
        r["ingredients"] = [ing(x) for x in r["ingredients"]]
    if r["type"] == HH + ":cutting":
        outs = []
        for res in r["result"]:
            try:
                res = dict(res)
                res["item"] = stack(res["item"])
                outs.append(res)
            except Dropped as e:
                REPORT["fd cutting result dropped"].append(str(e))
        if not outs:
            raise Dropped("no results")
        r["result"] = outs
        return r
    res = stack(r["result"])
    # Keep FD recipes making a ported FD item, or using one (canvas -> paper, bark -> compost, ...).
    uses_fd = '"farmersdelight:' in json.dumps(orig_ings) and any(
        ("hearthandharvest:" + x) in json.dumps({k: r[k] for k in ("key", "ingredients", "ingredient") if k in r})
        for x in re.findall(r'farmersdelight:([a-z0-9_/]+)', json.dumps(orig_ings)))
    if not res["id"].startswith(HH + ":") and not uses_fd:
        raise Dropped("result %s not an FD item of the bundle" % res["id"])
    r["result"] = res
    if "container" in r:
        r["container"] = stack(r["container"])
    return r


def write_tag_additions(path, tags):
    """Tags whose file Bountiful Fares' datagen also writes (src/main/generated): one jar can hold only
    one file per path, so BF's tag providers add HH's entries (BFItemTagProvider/BFBlockTagProvider)."""
    by_kind = {"item": [], "block": []}
    for key, values in tags.items():
        ns, rest = key.split(os.sep, 1)
        parts = rest.split(os.sep)            # tags/<kind>/<path...>.json
        kind = parts[1]
        tag = ns + ":" + "/".join(parts[2:])[:-5]
        by_kind[kind].append((tag, values))
    lines = ["package alabaster.hearthandharvest.datagen;", "",
             "import net.minecraft.core.registries.Registries;",
             "import net.minecraft.data.tags.TagAppender;",
             "import net.minecraft.resources.Identifier;",
             "import net.minecraft.resources.ResourceKey;",
             "import net.minecraft.tags.TagKey;",
             "import net.minecraft.world.item.Item;",
             "import net.minecraft.world.level.block.Block;", "",
             "import java.util.function.Function;", "",
             "/**",
             " * Hearth and Harvest (+ its Farmer's Delight pieces) entries of common/vanilla tags that Bountiful",
             " * Fares' datagen also writes. A jar holds one file per path, so BF's tag providers add these.",
             " * Generated by {@code _porting_tools/hh_data_migrate.py}.",
             " */",
             "public final class HHTagAdditions {",
             "    private HHTagAdditions() {", "    }", ""]
    for kind, cls, reg in (("item", "Item", "ITEM"), ("block", "Block", "BLOCK")):
        lines.append("    public static void add%sTags(Function<TagKey<%s>, TagAppender<%s>> builder) {" % (cls, cls, cls))
        for tag, values in sorted(by_kind[kind]):
            lines.append('        builder.apply(TagKey.create(Registries.%s, Identifier.parse("%s")))' % (reg, tag))
            for v in values:
                opt = False
                if isinstance(v, dict):
                    opt, v = not v.get("required", True), v["id"]
                if v.startswith("#"):
                    lines.append('                .addOptionalTag(TagKey.create(Registries.%s, Identifier.parse("%s")))' % (reg, v[1:]))
                else:
                    lines.append('                .%s(ResourceKey.create(Registries.%s, Identifier.parse("%s")))' % ("addOptional" if opt else "add", reg, v))
            lines[-1] += ";"
        lines += ["    }", ""]
    lines += ["}", ""]
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


def write_compostables(path, entries):
    lines = ["package alabaster.hearthandharvest.common.registry;", "",
             "import alabaster.hearthandharvest.HearthAndHarvest;",
             "import net.fabricmc.fabric.api.item.v1.DefaultItemComponentEvents;",
             "import net.hecco.bountifulfares.registry.util.BFRegistries;",
             "import net.minecraft.core.component.DataComponents;",
             "import net.minecraft.core.registries.BuiltInRegistries;",
             "import net.minecraft.world.item.component.Compostable;", "",
             "import java.util.LinkedHashMap;",
             "import java.util.Map;", "",
             "/**",
             " * Hearth and Harvest's composter chances (1.21.1: the NeoForge {@code compostables} data map) and",
             " * those of the Farmer's Delight items it now carries (FarmersDelightRefabricated's CompostableHelper).",
             " * 26.3 stores compostability as the {@code minecraft:compostable} item component; chances map onto",
             " * vanilla's tiers like Bountiful Fares' own (BFRegistries.compostBucketFor).",
             " * Generated by {@code _porting_tools/hh_data_migrate.py}; merged items are left to their own mod.",
             " */",
             "public final class HHCompostables {",
             "    private static final Map<String, Float> CHANCES = new LinkedHashMap<>();", "",
             "    static {"]
    for name, chance in sorted(entries):
        lines.append('        CHANCES.put("%s", %sF);' % (name, repr(float(chance))))
    lines += ["    }", "",
              "    private HHCompostables() {", "    }", "",
              "    public static void register() {",
              "        DefaultItemComponentEvents.MODIFY.register(context -> CHANCES.forEach((path, chance) ->",
              "                context.modify(BuiltInRegistries.ITEM.getValue(HearthAndHarvest.id(path)),",
              "                        builder -> builder.set(DataComponents.COMPOSTABLE, new Compostable(BFRegistries.compostBucketFor(chance))))));",
              "    }", "}", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


