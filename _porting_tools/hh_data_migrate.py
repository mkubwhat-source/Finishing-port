def ns_path(i):
    return i.split(":", 1) if ":" in i else ("minecraft", i)


def norm(i):
    return i if ":" in i else "minecraft:" + i


VANILLA_RENAMES = {"minecraft:chain": "minecraft:iron_chain"}  # renamed after 1.21.1
