def migrate_structure(src, dst):
    import nbtlib
    from nbtlib import Compound, String, Int, Byte, List
    f = nbtlib.load(src)
    pal = f["palette"]
    new_pal = []
    extra_be = {}  # palette index -> block entity nbt to add/replace

    def st(name, props=None):
        c = Compound({"Name": String(name)})
        if props:
            c["Properties"] = Compound({k: String(v) for k, v in props.items()})
        return c

    for idx, p in enumerate(pal):
        name = str(p["Name"])
        props = {k: str(v) for k, v in p.get("Properties", {}).items()}
        if name in ("hearthandharvest:trellis", "hearthandharvest:grape_trellis"):
            sides = [d for d in ("north", "south", "east", "west") if props.get("side_" + d) == "true"]
            if props.get("middle_ns") == "true":
                sides.append("east")
            if props.get("middle_ew") == "true":
                sides.append("north")
            plant = props.get("plant", "none")
            if not sides:
                # flat (floor/roof) trellis only: BF trellises are wall panels
                new_pal.append(st("minecraft:oak_trapdoor", {"facing": "north", "half": "bottom", "open": "false", "powered": "false", "waterlogged": "false"}))
                continue
            new_pal.append(st("bountifulfares:trellis", {"facing": sides[0], "waterlogged": "false"}))
            be = Compound({"id": String("bountifulfares:trellis_block_entity")})
            item = {"vine": "minecraft:vine", "rose": "minecraft:rose_bush", "red_grape": "hearthandharvest:red_grapes",
                    "green_grape": "hearthandharvest:green_grapes"}.get(plant)
            if item:
                be["Plant"] = Compound({"id": String(item), "count": Int(1)})
                if "grape" in plant:
                    # HH grape age 0..4 (ripe at 4) -> BF stage 0..5 (ripe at stages=5)
                    age = int(props.get("age", "0"))
                    be["Stage"] = Int(5 if age >= 4 else age)
            extra_be[idx] = be
            REPORT["structure trellis"].append("%s %s -> facing %s plant %s" % (name, sides, sides[0], plant))
            continue
        if name.startswith("farmersdelight:"):
            path = name.split(":", 1)[1]
            standins = {
                "stove": ("minecraft:smoker", {"facing": props.get("facing", "north"), "lit": "false"}),
                "tatami": ("minecraft:bamboo_mosaic", None),
                "rope_fence": ("minecraft:oak_fence", props),
                "purple_canvas_wall_sign": ("minecraft:pale_oak_wall_sign", props),
                "pink_canvas_wall_sign": ("minecraft:cherry_wall_sign", props),
                "wooden_basket": ("minecraft:barrel", {"facing": props.get("facing", "up"), "open": "false"}),
            }
            if path in standins:
                n, pr = standins[path]
                new_pal.append(st(n, pr))
                REPORT["structure stand-in"].append("%s -> %s" % (name, n))
                continue
            if path in HH_BLOCKS:
                new_pal.append(st(HH + ":" + path, props))
                continue
            raise ValueError("unhandled structure block " + name)
        if name.startswith(HH + ":") and name.split(":")[1] not in HH_BLOCKS:
            raise ValueError("structure block not registered: " + name)
        new_pal.append(p)
    f["palette"] = List[Compound](new_pal)

    be_ids = {"farmersdelight:cutting_board": HH + ":cutting_board", "farmersdelight:cabinet": HH + ":cabinet",
              "farmersdelight:basket": "minecraft:barrel", "farmersdelight:canvas_sign": "minecraft:sign",
              "farmersdelight:stove": None}
    for b in f["blocks"]:
        s = int(b["state"])
        if s in extra_be:
            b["nbt"] = copy.deepcopy(extra_be[s])
            continue
        n = b.get("nbt")
        if n is None:
            continue
        bid = str(n.get("id"))
        if bid in be_ids:
            if be_ids[bid] is None:
                del b["nbt"]
                continue
            n["id"] = String(be_ids[bid])
            if bid == "farmersdelight:basket":
                for k in list(n.keys()):
                    if k not in ("id", "LootTable", "LootTableSeed", "Items"):
                        del n[k]
        _remap_nbt_items(n)
    with gzip.GzipFile(dst, "wb", mtime=0) as g:   # deterministic output (no timestamp)
        f.write(g)


def _remap_nbt_items(n):
    from nbtlib import String
    if isinstance(n, dict):
        for k, v in n.items():
            if k == "id" and isinstance(v, str) and ("count" in n or "Count" in n):
                try:
                    n[k] = String(remap_item(str(v)))
                except Dropped:
                    pass
            else:
                _remap_nbt_items(v)
    elif isinstance(n, list):
        for v in n:
            _remap_nbt_items(v)


# ----------------------------------------------------------------------------- io helpers

WRITTEN = {}


def write(path, obj):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(obj, fh, indent=2)
        fh.write("\n")
    WRITTEN[path] = obj


def walk_json(root):
    for r, _, files in os.walk(root):
        for fn in sorted(files):
            if fn.endswith(".json"):
                p = os.path.join(r, fn)
                yield os.path.relpath(p, root), p


def java_ids(path, pattern):
    src = open(path).read()
    return set(re.findall(pattern, src))


